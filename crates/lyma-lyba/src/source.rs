//! Source file (`SRCF`) and source span (`SRCS`) helpers.

use crate::blob::{BlobId, BlobTable};
use crate::error::{ErrorContext, LybaError, Result};
use crate::policy::Limits;
use crate::primitives::UVar;
use crate::string_table::StringTable;

/// `SRCF`
pub const SOURCE_FILE_SECTION_NAME: &str = "SRCF";
/// `SRCS`
pub const SOURCE_SPAN_SECTION_NAME: &str = "SRCS";

/// Source URI is present.
pub const SOURCE_FILE_FLAG_URI_PRESENT: u64 = 1 << 0;
/// Display name is present.
pub const SOURCE_FILE_FLAG_DISPLAY_PRESENT: u64 = 1 << 1;
/// Embedded source blob reference is present.
pub const SOURCE_FILE_FLAG_SOURCE_BLOB_PRESENT: u64 = 1 << 2;
/// Digest blob reference is present.
pub const SOURCE_FILE_FLAG_DIGEST_PRESENT: u64 = 1 << 3;
/// Source is virtual and not backed by an external location.
pub const SOURCE_FILE_FLAG_VIRTUAL: u64 = 1 << 4;
/// Source is private and requires trusted reader policy.
pub const SOURCE_FILE_FLAG_PRIVATE: u64 = 1 << 5;
/// Source content was generated.
pub const SOURCE_FILE_FLAG_GENERATED: u64 = 1 << 6;
/// Reserved source-file flag bits.
pub const SOURCE_FILE_FLAG_RESERVED_MASK: u64 = !0x7f;

/// Span was generated by tooling.
pub const SOURCE_SPAN_FLAG_GENERATED: u64 = 1 << 0;
/// Span does not map directly to source bytes.
pub const SOURCE_SPAN_FLAG_SYNTHETIC: u64 = 1 << 1;
/// Span came from an include or assembly expansion.
pub const SOURCE_SPAN_FLAG_MACRO_OR_INCLUDE_EXPANSION: u64 = 1 << 2;
/// Span identifies source contributing to an evaluated expression result.
pub const SOURCE_SPAN_FLAG_EXPRESSION_RESULT: u64 = 1 << 3;
/// Reserved source-span flag bits.
pub const SOURCE_SPAN_FLAG_RESERVED_MASK: u64 = !0x0f;

/// One decoded `SRCF` record.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct SourceFileRecord {
    /// Stored flags.
    pub flags: u64,
    /// Optional inert source URI stored through `STRS`.
    pub uri: Option<String>,
    /// Optional user-facing display string stored through `STRS`.
    pub display: Option<String>,
    /// Optional embedded source content blob reference into `BLOB`.
    pub source_blob_ref: Option<BlobId>,
    /// Optional source digest blob reference into `BLOB`.
    pub digest_blob_ref: Option<BlobId>,
}

impl SourceFileRecord {
    /// Creates an empty source-file record.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Sets explicit flags.
    #[must_use]
    pub fn with_flags(mut self, flags: u64) -> Self {
        self.flags = flags;
        self
    }

    /// Sets an optional inert source URI.
    #[must_use]
    pub fn with_uri(mut self, uri: Option<String>) -> Self {
        self.uri = uri;
        self
    }

    /// Sets an optional display string.
    #[must_use]
    pub fn with_display(mut self, display: Option<String>) -> Self {
        self.display = display;
        self
    }

    /// Sets an optional embedded source blob reference.
    #[must_use]
    pub fn with_source_blob_ref(mut self, source_blob_ref: Option<BlobId>) -> Self {
        self.source_blob_ref = source_blob_ref;
        self
    }

    /// Sets an optional digest blob reference.
    #[must_use]
    pub fn with_digest_blob_ref(mut self, digest_blob_ref: Option<BlobId>) -> Self {
        self.digest_blob_ref = digest_blob_ref;
        self
    }

    /// Returns whether a source URI is present.
    #[must_use]
    pub const fn has_uri(&self) -> bool {
        self.flags & SOURCE_FILE_FLAG_URI_PRESENT != 0
    }

    /// Returns whether a display string is present.
    #[must_use]
    pub const fn has_display(&self) -> bool {
        self.flags & SOURCE_FILE_FLAG_DISPLAY_PRESENT != 0
    }

    /// Returns whether an embedded source blob reference is present.
    #[must_use]
    pub const fn has_source_blob(&self) -> bool {
        self.flags & SOURCE_FILE_FLAG_SOURCE_BLOB_PRESENT != 0
    }

    /// Returns whether a digest blob reference is present.
    #[must_use]
    pub const fn has_digest(&self) -> bool {
        self.flags & SOURCE_FILE_FLAG_DIGEST_PRESENT != 0
    }

    /// Returns whether the source is virtual.
    #[must_use]
    pub const fn is_virtual(&self) -> bool {
        self.flags & SOURCE_FILE_FLAG_VIRTUAL != 0
    }

    /// Returns whether the source is private.
    #[must_use]
    pub const fn is_private(&self) -> bool {
        self.flags & SOURCE_FILE_FLAG_PRIVATE != 0
    }

    /// Returns whether the source is generated.
    #[must_use]
    pub const fn is_generated(&self) -> bool {
        self.flags & SOURCE_FILE_FLAG_GENERATED != 0
    }

    fn normalized_flags(&self) -> u64 {
        normalize_flags(
            self.flags,
            self.uri.is_some(),
            self.display.is_some(),
            self.source_blob_ref.is_some(),
            self.digest_blob_ref.is_some(),
        )
    }
}

/// In-memory `SRCF` table.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct SourceFileTable {
    /// Ordered source-file records.
    pub records: Vec<SourceFileRecord>,
}

impl SourceFileTable {
    /// Creates an empty table.
    #[must_use]
    pub fn new() -> Self {
        Self::default()
    }

    /// Appends a record.
    #[must_use]
    pub fn with_record(mut self, record: SourceFileRecord) -> Self {
        self.records.push(record);
        self
    }

    /// Returns the record count.
    #[must_use]
    pub fn len(&self) -> usize {
        self.records.len()
    }

    /// Returns whether the table is empty.
    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.records.is_empty()
    }
}

/// One decoded `SRCS` record.
#[derive(Debug, Clone, PartialEq, Eq, Hash, Default)]
pub struct SourceSpanRecord {
    /// Zero-based source-file reference into `SRCF`.
    pub source_file_ref: u64,
    /// Zero-based UTF-8 byte offset into the source.
    pub byte_offset: u64,
    /// UTF-8 byte length of the half-open span.
    pub byte_length: u64,
    /// One-based starting line.
    pub start_line: u64,
    /// One-based starting column.
    pub start_column: u64,
    /// One-based ending line.
    pub end_line: u64,
    /// One-based ending column.
    pub end_column: u64,
    /// Stored raw span flags.
    pub flags: u64,
}

impl SourceSpanRecord {
    /// Creates a span record with required byte-range fields.
    #[must_use]
    pub fn new(source_file_ref: u64, byte_offset: u64, byte_length: u64) -> Self {
        Self {
            source_file_ref,
            byte_offset,
            byte_length,
            start_line: 1,
            start_column: 1,
            end_line: 1,
            end_column: 1,
            flags: 0,
        }
    }

    /// Sets the source-file reference.
    #[must_use]
    pub fn with_source_file_ref(mut self, source_file_ref: u64) -> Self {
        self.source_file_ref = source_file_ref;
        self
    }

    /// Sets the byte offset.
    #[must_use]
    pub fn with_byte_offset(mut self, byte_offset: u64) -> Self {
        self.byte_offset = byte_offset;
        self
    }

    /// Sets the byte length.
    #[must_use]
    pub fn with_byte_length(mut self, byte_length: u64) -> Self {
        self.byte_length = byte_length;
        self
    }

    /// Sets the one-based start position.
    #[must_use]
    pub fn with_start_position(mut self, line: u64, column: u64) -> Self {
        self.start_line = line;
        self.start_column = column;
        self
    }

    /// Sets the one-based end position.
    #[must_use]
    pub fn with_end_position(mut self, line: u64, column: u64) -> Self {
        self.end_line = line;
        self.end_column = column;
        self
    }

    /// Sets stored raw flags.
    #[must_use]
    pub fn with_flags(mut self, flags: u64) -> Self {
        self.flags = flags;
        self
    }

    /// Returns the exclusive end byte offset when it fits in `u64`.
    #[must_use]
    pub fn byte_end(&self) -> Option<u64> {
        self.byte_offset.checked_add(self.byte_length)
    }

    /// Returns whether the span is marked generated.
    #[must_use]
    pub const fn is_generated(&self) -> bool {
        self.flags & SOURCE_SPAN_FLAG_GENERATED != 0
    }

    /// Returns whether the span is marked synthetic.
    #[must_use]
    pub const fn is_synthetic(&self) -> bool {
        self.flags & SOURCE_SPAN_FLAG_SYNTHETIC != 0
    }

    /// Returns whether the span is marked as macro/include expansion.
    #[must_use]
    pub const fn is_macro_or_include_expansion(&self) -> bool {
        self.flags & SOURCE_SPAN_FLAG_MACRO_OR_INCLUDE_EXPANSION != 0
    }

    /// Returns whether the span is marked as an expression result.
    #[must_use]
    pub const fn is_expression_result(&self) -> bool {
        self.flags & SOURCE_SPAN_FLAG_EXPRESSION_RESULT != 0
    }

    /// Converts the stored byte range into a syntax-layer span when values fit.
    #[must_use]
    pub fn to_lyma_syntax_span(&self) -> Option<lyma_syntax::Span> {
        let file_id = u32::try_from(self.source_file_ref).ok()?;
        let start = usize::try_from(self.byte_offset).ok()?;
        let end = usize::try_from(self.byte_end()?).ok()?;
        Some(lyma_syntax::Span::new(
            lyma_syntax::FileId(file_id),
            start,
            end,
        ))
    }

    /// Converts the stored start position into a syntax-layer position when values fit.
    #[must_use]
    pub fn start_position_to_lyma_syntax(&self) -> Option<lyma_syntax::SourcePosition> {
        Some(lyma_syntax::SourcePosition {
            line: usize::try_from(self.start_line).ok()?,
            column: usize::try_from(self.start_column).ok()?,
        })
    }

    /// Converts the stored end position into a syntax-layer position when values fit.
    #[must_use]
    pub fn end_position_to_lyma_syntax(&self) -> Option<lyma_syntax::SourcePosition> {
        Some(lyma_syntax::SourcePosition {
            line: usize::try_from(self.end_line).ok()?,
            column: usize::try_from(self.end_column).ok()?,
        })
    }

    /// Builds a stored span record from syntax-layer span and positions when values fit.
    #[must_use]
    pub fn from_lyma_syntax(
        span: lyma_syntax::Span,
        start: lyma_syntax::SourcePosition,
        end: lyma_syntax::SourcePosition,
    ) -> Option<Self> {
        Some(
            Self::new(
                u64::from(span.file_id.0),
                u64::try_from(span.start).ok()?,
                u64::try_from(span.end.checked_sub(span.start)?).ok()?,
            )
            .with_start_position(
                u64::try_from(start.line).ok()?,
                u64::try_from(start.column).ok()?,
            )
            .with_end_position(
                u64::try_from(end.line).ok()?,
                u64::try_from(end.column).ok()?,
            ),
        )
    }
}

