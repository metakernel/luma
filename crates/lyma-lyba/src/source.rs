pub(crate) fn decode_source_file_table(
    payload: &[u8],
    limits: &Limits,
    strings: &StringTable,
    blob_count: usize,
) -> Result<SourceFileTable> {
    let mut offset = 0_usize;
    let source_count = usize::try_from(UVar::decode(payload, &mut offset)?.0)
        .map_err(|_| LybaError::limit_exceeded("source file count exceeds configured maximum"))?;
    if source_count > limits.max_table_record_count {
        return Err(LybaError::limit_exceeded(
            "source file count exceeds configured maximum",
        ));
    }

    let mut records = Vec::with_capacity(source_count);
    for record_index in 0..source_count {
        let flags_offset = offset;
        let flags = UVar::decode(payload, &mut offset)?.0;
        if flags & SOURCE_FILE_FLAG_RESERVED_MASK != 0 {
            return Err(LybaError::InvalidReservedFlags(
                ErrorContext::new("reserved source file flag bits were non-zero")
                    .with_byte_offset(flags_offset)
                    .with_record_index(record_index),
            ));
        }
        let uri = decode_string_ref(payload, &mut offset, strings, record_index, "source URI")?;
        let display = decode_string_ref(
            payload,
            &mut offset,
            strings,
            record_index,
            "source display",
        )?;
        let source_blob_ref = decode_blob_ref(
            payload,
            &mut offset,
            blob_count,
            record_index,
            "source blob",
        )?;
        let digest_blob_ref = decode_blob_ref(
            payload,
            &mut offset,
            blob_count,
            record_index,
            "source digest",
        )?;

        records.push(SourceFileRecord {
            flags: normalize_flags(
                flags,
                uri.is_some(),
                display.is_some(),
                source_blob_ref.is_some(),
                digest_blob_ref.is_some(),
            ),
            uri: uri.map(|string_id| strings.strings[string_id as usize].value.clone()),
            display: display.map(|string_id| strings.strings[string_id as usize].value.clone()),
            source_blob_ref: source_blob_ref.map(BlobId),
            digest_blob_ref: digest_blob_ref.map(BlobId),
        });
    }

    if offset != payload.len() {
        return Err(LybaError::InvalidSectionTable(
            ErrorContext::new("source file table payload had trailing bytes")
                .with_byte_offset(offset),
        ));
    }

    Ok(SourceFileTable { records })
}

pub(crate) fn encode_source_file_table(
    table: &SourceFileTable,
    strings: &StringTable,
    blob_count: usize,
) -> Result<Vec<u8>> {
    let mut bytes = Vec::new();
    UVar(table.records.len() as u64).encode_into(&mut bytes);

    for (record_index, record) in table.records.iter().enumerate() {
        let flags = record.normalized_flags();
        if flags & SOURCE_FILE_FLAG_RESERVED_MASK != 0 {
            return Err(LybaError::InvalidReservedFlags(
                ErrorContext::new("reserved source file flag bits were non-zero")
                    .with_record_index(record_index),
            ));
        }

        UVar(flags).encode_into(&mut bytes);
        UVar(encode_string_ref(
            record.uri.as_deref(),
            strings,
            record_index,
            "source URI",
        )?)
        .encode_into(&mut bytes);
        UVar(encode_string_ref(
            record.display.as_deref(),
            strings,
            record_index,
            "source display",
        )?)
        .encode_into(&mut bytes);
        UVar(encode_blob_ref(
            record.source_blob_ref,
            blob_count,
            record_index,
            "source blob",
        )?)
        .encode_into(&mut bytes);
        UVar(encode_blob_ref(
            record.digest_blob_ref,
            blob_count,
            record_index,
            "source digest",
        )?)
        .encode_into(&mut bytes);
    }

    Ok(bytes)
}

pub(crate) fn decode_source_span_table(
    payload: &[u8],
    limits: &Limits,
    source_files: &SourceFileTable,
    blobs: Option<&BlobTable>,
) -> Result<SourceSpanTable> {
    let mut offset = 0_usize;
    let span_count = usize::try_from(UVar::decode(payload, &mut offset)?.0)
        .map_err(|_| LybaError::limit_exceeded("source span count exceeds configured maximum"))?;
    if span_count > limits.max_table_record_count {
        return Err(LybaError::limit_exceeded(
            "source span count exceeds configured maximum",
        ));
    }

    let mut records = Vec::with_capacity(span_count);
    for record_index in 0..span_count {
        let source_file_ref = decode_source_file_ref(
            payload,
            &mut offset,
            source_files.records.len(),
            record_index,
        )?;
        let byte_offset = decode_uvar(payload, &mut offset)?;
        let byte_length = decode_uvar(payload, &mut offset)?;
        let start_line = decode_uvar(payload, &mut offset)?;
        let start_column = decode_uvar(payload, &mut offset)?;
        let end_line = decode_uvar(payload, &mut offset)?;
        let end_column = decode_uvar(payload, &mut offset)?;
        let flags_offset = offset;
        let flags = decode_uvar(payload, &mut offset)?;

        let record = SourceSpanRecord {
            source_file_ref,
            byte_offset,
            byte_length,
            start_line,
            start_column,
            end_line,
            end_column,
            flags,
        };
        validate_source_span_record(
            &record,
            source_files,
            blobs,
            record_index,
            Some(flags_offset),
        )?;
        records.push(record);
    }

    if offset != payload.len() {
        return Err(LybaError::InvalidSectionTable(
            ErrorContext::new("source span table payload had trailing bytes")
                .with_byte_offset(offset),
        ));
    }

    Ok(SourceSpanTable { records })
}

pub(crate) fn encode_source_span_table(
    table: &SourceSpanTable,
    limits: &Limits,
    source_files: &SourceFileTable,
    blobs: Option<&BlobTable>,
) -> Result<Vec<u8>> {
    if table.records.len() > limits.max_table_record_count {
        return Err(LybaError::limit_exceeded(
            "source span count exceeds configured maximum",
        ));
    }

    let mut bytes = Vec::new();
    UVar(table.records.len() as u64).encode_into(&mut bytes);

    for (record_index, record) in table.records.iter().enumerate() {
        validate_source_span_record(record, source_files, blobs, record_index, None)?;
        UVar(record.source_file_ref).encode_into(&mut bytes);
        UVar(record.byte_offset).encode_into(&mut bytes);
        UVar(record.byte_length).encode_into(&mut bytes);
        UVar(record.start_line).encode_into(&mut bytes);
        UVar(record.start_column).encode_into(&mut bytes);
        UVar(record.end_line).encode_into(&mut bytes);
        UVar(record.end_column).encode_into(&mut bytes);
        UVar(record.flags).encode_into(&mut bytes);
    }

    Ok(bytes)
}

fn normalize_flags(
    flags: u64,
    has_uri: bool,
    has_display: bool,
    has_source_blob: bool,
    has_digest: bool,
) -> u64 {
    let mut flags = flags;
    if has_uri {
        flags |= SOURCE_FILE_FLAG_URI_PRESENT;
    } else {
        flags &= !SOURCE_FILE_FLAG_URI_PRESENT;
    }
    if has_display {
        flags |= SOURCE_FILE_FLAG_DISPLAY_PRESENT;
    } else {
        flags &= !SOURCE_FILE_FLAG_DISPLAY_PRESENT;
    }
    if has_source_blob {
        flags |= SOURCE_FILE_FLAG_SOURCE_BLOB_PRESENT;
    } else {
        flags &= !SOURCE_FILE_FLAG_SOURCE_BLOB_PRESENT;
    }
    if has_digest {
        flags |= SOURCE_FILE_FLAG_DIGEST_PRESENT;
    } else {
        flags &= !SOURCE_FILE_FLAG_DIGEST_PRESENT;
    }
    flags
}

fn decode_string_ref(
    payload: &[u8],
    offset: &mut usize,
    strings: &StringTable,
    record_index: usize,
    kind: &str,
) -> Result<Option<u64>> {
    let encoded = UVar::decode(payload, offset)?.0;
    if encoded == 0 {
        return Ok(None);
    }
    let string_ref = encoded - 1;
    if string_ref >= strings.strings.len() as u64 {
        return Err(LybaError::InvalidValueReference(
            ErrorContext::new(format!("{kind} string reference was out of range"))
                .with_record_index(record_index),
        ));
    }
    Ok(Some(string_ref))
}

fn encode_string_ref(
    value: Option<&str>,
    strings: &StringTable,
    record_index: usize,
    kind: &str,
) -> Result<u64> {
    let Some(value) = value else {
        return Ok(0);
    };
    strings
        .strings
        .iter()
        .position(|record| record.value == value)
        .ok_or_else(|| {
            LybaError::InvalidValueReference(
                ErrorContext::new(format!("{kind} string was not present in STRS"))
                    .with_record_index(record_index),
            )
        })
        .and_then(|index| {
            u64::try_from(index)
                .ok()
                .and_then(|index| index.checked_add(1))
                .ok_or_else(|| {
                    LybaError::invalid_section_table("source string reference overflowed u64")
                })
        })
}

fn decode_blob_ref(
    payload: &[u8],
    offset: &mut usize,
    blob_count: usize,
    record_index: usize,
    kind: &str,
) -> Result<Option<u64>> {
    let encoded = UVar::decode(payload, offset)?.0;
    if encoded == 0 {
        return Ok(None);
    }
    let blob_ref = encoded - 1;
    if blob_ref >= blob_count as u64 {
        return Err(LybaError::InvalidValueReference(
            ErrorContext::new(format!("{kind} reference was out of range"))
                .with_record_index(record_index),
        ));
    }
    Ok(Some(blob_ref))
}

fn encode_blob_ref(
    blob_ref: Option<BlobId>,
    blob_count: usize,
    record_index: usize,
    kind: &str,
) -> Result<u64> {
    let Some(blob_ref) = blob_ref else {
        return Ok(0);
    };
    if blob_ref.0 >= blob_count as u64 {
        return Err(LybaError::InvalidValueReference(
            ErrorContext::new(format!("{kind} reference was out of range"))
                .with_record_index(record_index),
        ));
    }
    blob_ref
        .0
        .checked_add(1)
        .ok_or_else(|| LybaError::invalid_section_table("source blob reference overflowed u64"))
}

fn validate_source_span_record(
    record: &SourceSpanRecord,
    source_files: &SourceFileTable,
    blobs: Option<&BlobTable>,
    record_index: usize,
    flags_offset: Option<usize>,
) -> Result<()> {
    if record.flags & SOURCE_SPAN_FLAG_RESERVED_MASK != 0 {
        let context = ErrorContext::new("reserved source span flag bits were non-zero")
            .with_record_index(record_index);
        let context = if let Some(flags_offset) = flags_offset {
            context.with_byte_offset(flags_offset)
        } else {
            context
        };
        return Err(LybaError::InvalidReservedFlags(context));
    }
    if record.start_line == 0
        || record.start_column == 0
        || record.end_line == 0
        || record.end_column == 0
    {
        return Err(LybaError::InvalidSourceSpan(
            ErrorContext::new("source span lines and columns must be one-based")
                .with_record_index(record_index),
        ));
    }
    let source_file_index = usize::try_from(record.source_file_ref).map_err(|_| {
        LybaError::InvalidValueReference(
            ErrorContext::new("source span source file reference exceeded platform limits")
                .with_record_index(record_index),
        )
    })?;
    let source_file = source_files.records.get(source_file_index).ok_or_else(|| {
        LybaError::InvalidValueReference(
            ErrorContext::new(format!(
                "source span source file reference {} was out of range for SRCF count {}",
                record.source_file_ref,
                source_files.records.len()
            ))
            .with_record_index(record_index),
        )
    })?;
    let byte_end = record.byte_end().ok_or_else(|| {
        LybaError::InvalidSourceSpan(
            ErrorContext::new("source span byte range overflowed").with_record_index(record_index),
        )
    })?;

    if let (Some(blob_ref), Some(blobs)) = (source_file.source_blob_ref, blobs) {
        let blob = blobs.get(blob_ref).ok_or_else(|| {
            LybaError::InvalidValueReference(
                ErrorContext::new(format!(
                    "source span referenced embedded source blob {} that was not present",
                    blob_ref.0
                ))
                .with_record_index(record_index),
            )
        })?;
        let blob_len = u64::try_from(blob.len()).unwrap_or(u64::MAX);
        if byte_end > blob_len {
            return Err(LybaError::InvalidSourceSpan(
                ErrorContext::new(format!(
                    "source span byte range {}..{} was outside embedded source length {}",
                    record.byte_offset, byte_end, blob_len
                ))
                .with_record_index(record_index),
            ));
        }
    }

    Ok(())
}

fn decode_source_file_ref(
    payload: &[u8],
    offset: &mut usize,
    source_count: usize,
    record_index: usize,
) -> Result<u64> {
    let source_file_ref = decode_uvar(payload, offset)?;
    let source_file_index = usize::try_from(source_file_ref).map_err(|_| {
        LybaError::InvalidValueReference(
            ErrorContext::new("source span source file reference exceeded platform limits")
                .with_record_index(record_index),
        )
    })?;
    if source_file_index >= source_count {
        return Err(LybaError::InvalidValueReference(
            ErrorContext::new(format!(
                "source span source file reference {source_file_ref} was out of range for SRCF count {source_count}"
            ))
            .with_record_index(record_index),
        ));
    }
    Ok(source_file_ref)
}

fn decode_uvar(payload: &[u8], offset: &mut usize) -> Result<u64> {
    Ok(UVar::decode(payload, offset)?.0)
}
